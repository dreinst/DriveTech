-- =============================================================================
-- Jalan sehat berbayar Rp10.000 per orang.
--
-- jalan_sehat_pesanan: satu pendaftaran (web atau chat WhatsApp kantor) untuk N peserta, dibayar lewat QRIS
--   DriveTech sebesar N x harga + kode unik 1..349 (lapak memakai 350..999, jadi nominal keduanya tidak pernah
--   sama). status: menunggu (belum ada bukti) -> dicek (bukti masuk) -> lunas, atau batal (lewat batas bayar).
--   kabar terisi saat ada kabar untuk bot WhatsApp ('lunas' kirim tiket, 'ditolak' minta bukti ulang).
-- jalan_sehat_peserta: satu baris = satu tiket undian, nomor tiket = id. Tiket pesanan dibuat saat pesanan
--   diverifikasi lunas. Tiket 'tempat' dicetak kosong untuk dijual tunai di lokasi dan baru aktif (ikut undian)
--   setelah ditandai terjual di panel admin.
-- Jalankan: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/migrasi/20261029-jalan-sehat-berbayar.sql
-- =============================================================================
begin;

create table if not exists public.jalan_sehat_pesanan (
    id bigint generated by default as identity primary key,
    kode text default ('JS-' || upper(encode(public.gen_random_bytes(4), 'hex'))) not null unique,
    token text default encode(public.gen_random_bytes(16), 'hex') not null unique,
    nama text not null,
    phone text not null,
    domisili text not null,
    jumlah integer not null constraint jalan_sehat_pesanan_jumlah_check check (jumlah > 0),
    amount integer not null,
    unique_code integer constraint jalan_sehat_pesanan_kode_unik_check check (unique_code between 1 and 349),
    sumber text not null constraint jalan_sehat_pesanan_sumber_check check (sumber in ('web', 'wa')),
    status text default 'menunggu' not null
        constraint jalan_sehat_pesanan_status_check check (status in ('menunggu', 'dicek', 'lunas', 'batal')),
    batas_bayar timestamp with time zone not null,
    proof_url text,
    submitted_at timestamp with time zone,
    verified_at timestamp with time zone,
    alasan_tolak text,
    wa_chat text,
    kabar text constraint jalan_sehat_pesanan_kabar_check check (kabar in ('lunas', 'ditolak')),
    created_at timestamp with time zone default now() not null
);
create index if not exists jalan_sehat_pesanan_phone_idx on public.jalan_sehat_pesanan (phone);

-- Belum ada pendaftar di produksi saat migrasi ini dibuat, jadi aturan lama (satu nomor satu pendaftaran) dibuang.
alter table public.jalan_sehat_peserta
    drop constraint if exists jalan_sehat_peserta_phone_key,
    alter column nama drop not null,
    alter column phone drop not null,
    alter column domisili drop not null,
    add column if not exists pesanan_id bigint references public.jalan_sehat_pesanan (id),
    add column if not exists sumber text default 'web' not null,
    add column if not exists aktif boolean default true not null,
    add column if not exists dicetak_at timestamp with time zone;
alter table public.jalan_sehat_peserta drop constraint if exists jalan_sehat_peserta_sumber_check;
alter table public.jalan_sehat_peserta
    add constraint jalan_sehat_peserta_sumber_check check (sumber in ('web', 'wa', 'tempat'));
create index if not exists jalan_sehat_peserta_pesanan_idx on public.jalan_sehat_peserta (pesanan_id);

-- Kode unik pesanan jalan sehat: nominal transfernya tidak sama dengan pesanan lain yang belum lunas.
create or replace function public.alokasi_kode_unik_js(p_pesanan bigint) returns integer
    language plpgsql security definer
    set search_path to 'public'
    as $$
declare
  v_amount int;
  v_code   int;
  v_free   int[];
begin
  perform pg_advisory_xact_lock(hashtext('drivetech:kode_unik_js'));

  select amount, unique_code into v_amount, v_code
    from public.jalan_sehat_pesanan where id = p_pesanan for update;
  if not found then raise exception 'pesanan % tidak ditemukan', p_pesanan; end if;
  if v_code is not null then return v_code; end if;

  select array_agg(c) into v_free
    from generate_series(1, 349) c
   where not exists (
     select 1 from public.jalan_sehat_pesanan p
      where p.id <> p_pesanan
        and p.unique_code is not null
        and p.status in ('menunggu', 'dicek')
        and p.amount + p.unique_code = v_amount + c
   );
  if v_free is null then return null; end if;

  v_code := v_free[1 + floor(random() * array_length(v_free, 1))::int];
  update public.jalan_sehat_pesanan set unique_code = v_code where id = p_pesanan;
  return v_code;
end $$;

commit;
