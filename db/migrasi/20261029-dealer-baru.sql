-- =============================================================================
-- Formulir pendaftaran dan komitmen dealer mobil dan motor baru (/dealer).
-- data = isian formulir, kuncinya sama dengan nama kolom PDF (lib/domain/formulir-dealer.ts).
-- ttd = PNG tanda tangan dealer, stempel = foto stempel (JPEG/PNG, opsional).
-- Tanda tangan boleh menyusul dari perangkat lain lewat /dealer/<token>.
-- diterima_at terisi saat panitia menerima; tanda tangan panitia lalu muncul di PDF.
-- Jalankan: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/migrasi/20261029-dealer-baru.sql
-- =============================================================================
begin;

create table if not exists public.dealer_pendaftaran (
    id bigint generated by default as identity primary key,
    token text default encode(public.gen_random_bytes(16), 'hex') not null unique,
    data jsonb not null,
    ttd bytea,
    stempel bytea,
    ditandatangani_at timestamp with time zone,
    diterima_at timestamp with time zone,
    created_at timestamp with time zone default now() not null
);

commit;
