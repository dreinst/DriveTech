-- =============================================================================
-- Pendaftaran jalan sehat + kupon doorprize (Minggu 8 November 2026).
-- Satu nomor WhatsApp satu pendaftaran. Nomor kupon = id (JS-0001, JS-0002, ...).
-- token dipakai di alamat halaman kupon supaya kupon orang lain tidak bisa ditebak.
-- menang_at terisi saat peserta terpilih di undian, jadi tidak terpilih dua kali.
-- Jalankan: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/migrasi/20261028-jalan-sehat.sql
-- =============================================================================
begin;

create table if not exists public.jalan_sehat_peserta (
    id bigint generated by default as identity primary key,
    nama text not null,
    phone text not null unique,
    domisili text not null,
    token text default encode(public.gen_random_bytes(16), 'hex') not null unique,
    menang_at timestamp with time zone,
    created_at timestamp with time zone default now() not null
);

commit;
